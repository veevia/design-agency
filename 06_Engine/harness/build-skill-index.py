#!/usr/bin/env python3
"""build-skill-index.py — generate the capability catalog at 03_Agents-and-Skills/INDEX.md.

The catalog lists every capability an agent can select: native skills, agents, prompts and SOPs,
host adapters waiting for a plug-in, plug-in profiles, and the capabilities of plugged-in plug-ins.
Output is deterministic (no dates), so `--check` is a reliable drift gate.

    python3 06_Engine/harness/build-skill-index.py           # write INDEX.md
    python3 06_Engine/harness/build-skill-index.py --check   # exit 1 when INDEX.md is stale
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ENGINE_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE_DIR))

from agency.catalog import build_catalog  # noqa: E402
from agency.config import SOPS_DIR  # noqa: E402
from agency.plugins import edition_of_source, read_gitmodules  # noqa: E402
from agency.report import front_matter  # noqa: E402

INDEX = Path("03_Agents-and-Skills/INDEX.md")
HEADER = "<!-- GENERATED by 06_Engine/harness/build-skill-index.py; do not hand-edit. Rebuild after adding a capability. -->"
# A pinned plug-in that is not checked out keeps its last generated section while the pin is unchanged, so every
# clone renders the same file. CI checks plug-ins out and regenerates the sections from their content.
SECTION = re.compile(r"<!-- plugin:(?P<name>[a-z0-9]+(?:-[a-z0-9]+)*)(?: pin:(?P<pin>[0-9a-f]{7,64}))? -->\n"
                     r"(?P<body>.*?)\n<!-- /plugin:(?P=name) -->", re.S)
# Engines check bound skills by finding the name between backticks, slashes or brackets anywhere in this file
# (PDG: (`|/|\[)name(`|/|\])). Only skill names are written that way; every other name and all free text avoid it.
SLASHED_WORD = re.compile(r"(?<=/)(?=[a-z0-9]+(?:-[a-z0-9]+)*/)")


def cell(text: object, limit: int = 200) -> str:
    value = " ".join(str(text or "").split()).replace("|", "\\|")
    return value if len(value) <= limit else value[: limit - 1].rstrip() + "…"


def prose(text: object, limit: int = 200) -> str:
    """Free text in a table cell, unable to pass for a listed skill name."""
    value = cell(text, limit).replace("`", "").replace("[", "(").replace("]", ")")
    return SLASHED_WORD.sub(" ", value)


def label(name: str) -> str:
    """A name that is not a skill (plug-in, agent, prompt, adapter): bold, never between delimiters."""
    return f"**{name}**"


def link(root: Path, path: Path, label: str) -> str:
    return f"[{label}]({os.path.relpath(path, root / INDEX.parent).replace(os.sep, '/')})"


def meta(path: Path) -> dict:
    data, _ = front_matter(path) if path.is_file() else (None, None)
    return data or {}


def _git(cwd: Path, *args: str) -> str | None:
    try:
        result = subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def checkout_pin(mount: Path) -> str | None:
    """Commit checked out in a mount that is its own git checkout (not the host's)."""
    out = _git(mount, "rev-parse", "--show-toplevel", "HEAD")
    if not out or len(out.splitlines()) != 2:
        return None
    toplevel, head = out.splitlines()
    return head if Path(toplevel).resolve() == mount.resolve() else None


def registered_pin(root: Path, mount: str) -> str | None:
    """Commit the host records for a submodule (its gitlink), without needing a checkout."""
    out = _git(root, "ls-files", "-s", "--", mount)
    fields = out.split() if out else []
    return fields[1] if len(fields) >= 2 and fields[0] == "160000" else None


def plugin_skill_sections(root: Path, catalog) -> list[str]:
    """Skills of the plug-ins pinned here, as names (engines such as PDG check bound skills against this list)."""
    path = root / INDEX
    previous = ({m["name"]: (m["pin"], m["body"]) for m in SECTION.finditer(path.read_text(encoding="utf-8"))}
                if path.is_file() else {})
    out: list[str] = []
    for name, state in catalog.states.items():
        if state.override.enabled is False:
            continue
        if state.enabled:
            pin = checkout_pin(state.path)
            mine = [item for item in catalog.items if item.origin == name]
            skills = sorted((item for item in mine if item.surface == "skills"), key=lambda item: item.name)
            others = Counter(item.surface for item in mine if item.surface != "skills")
            lines = [f"Edition {label(state.edition or '-')} · {len(skills)} skills"
                     + "".join(f" · {count} {surface.replace('_', ' ')}" for surface, count in sorted(others.items())),
                     "", "| Skill | Use it to |", "|---|---|"]
            lines += [f"| `{item.name}` | {prose(meta(item.source / 'SKILL.md').get('description'))} |" for item in skills]
            body = "\n".join(lines)
        elif state.registered:
            pin = registered_pin(root, str(state.mount))
            kept_pin, kept_body = previous.get(name, (None, None))
            if kept_body is not None and kept_pin == pin:
                body = kept_body
            else:  # new or re-pinned while not checked out: its skill list is unknown here
                body = (f"Pinned{' at ' + label(pin[:12]) if pin else ''} but not checked out here; "
                        f"python3 06_Engine/scripts/agency.py plugin add {name} lists its skills.")
        else:
            continue
        marker = f"<!-- plugin:{name}{' pin:' + pin if pin else ''} -->"
        out += [f"### {name}", "", marker, body, f"<!-- /plugin:{name} -->", ""]
    return out


def render(root: Path) -> str:
    catalog = build_catalog(root)
    native = [item for item in catalog.items if item.origin == "native"]
    skills = sorted((i for i in native if i.surface == "skills"), key=lambda i: i.name)
    agents = sorted((i for i in native if i.surface == "agents"), key=lambda i: i.name)
    prompts = sorted((i for i in native if i.surface == "prompts"), key=lambda i: i.name)
    sops = sorted(p for p in (root / SOPS_DIR).glob("*/SOP.md") if not p.parent.name.startswith("_"))
    gated_sops = catalog.gated.get("sops", {})
    out = [
        HEADER,
        "",
        "# Capability catalog",
        "",
        "**TL;DR:** Search this list, then load only the capability the task needs; the catalog is a "
        "discovery index, not default context.",
        "",
        f"Native: **{len(skills)}** skills · **{len(agents)}** agents · **{len(prompts)}** prompts · "
        f"**{len(sops)}** SOPs. Plug-in profiles: **{len(catalog.states)}** "
        f"({sum(s.in_repository for s in catalog.states.values())} in this repository).",
        "",
        "Find a capability with `rg -n -i \"<keyword>\" 03_Agents-and-Skills/INDEX.md`. Runtimes discover the same "
        "capabilities through generated links in `.github/` and `.claude/` (`python3 06_Engine/scripts/agency.py sync`).",
        "",
        "## Native skills",
        "",
        "| Skill | Status | Contract | Use it to |",
        "|---|---|---|---|",
    ]
    for item in skills:
        data = meta(item.source / "SKILL.md")
        fields = {**(data.get("metadata") or {}), **data} if isinstance(data.get("metadata"), dict) else data
        mode = "exempt" if fields.get("contract-exempt") else ("executable" if fields.get("lints") else "-")
        out.append(f"| {link(root, item.source / 'SKILL.md', item.name)} | {cell(data.get('status', '-'))} | {mode} | "
                   f"{prose(data.get('description'))} |")
    out += ["", "## Native agents", "", "| Agent | Use it to |", "|---|---|"]
    for item in agents:
        data = meta(item.source)
        out.append(f"| {link(root, item.source, label(item.name))} | {prose(data.get('description'))} |")
    out += ["", "## Prompts", "", "| Prompt | Use it to |", "|---|---|"]
    for item in prompts:
        data = meta(item.source)
        out.append(f"| {link(root, item.source, label('/' + item.name))} | {prose(data.get('description'))} |")
    out += ["", "## SOPs", "", "| SOP | Status | Trigger |", "|---|---|---|"]
    for path in sops:
        if path.parent.name in gated_sops:
            continue  # listed with the host adapters waiting for their plug-in
        data = meta(path)
        out.append(f"| {link(root, path, label(path.parent.name))} | {cell(data.get('status', '-'))} | {prose(data.get('trigger'))} |")
    waiting = sorted((surface, name, plugin) for surface, names in catalog.gated.items() for name, plugin in names.items())
    out += ["", "## Host adapters waiting for a plug-in", ""]
    if waiting:
        out += ["These native files drive a plug-in. Discovery exposes them once the plug-in is added.", "",
                "| Adapter | Surface | Plug-in |", "|---|---|---|"]
        out += [f"| {label(name)} | {surface} | {label(plugin)} |" for surface, name, plugin in waiting]
    else:
        out.append("None: every host adapter's plug-in is plugged in.")
    sections = plugin_skill_sections(root, catalog)
    out += ["", "## Plug-in skills", ""]
    if sections:
        out += ["Skills from the plug-ins pinned in this repository. Runtimes load them through `.github/skills/` and "
                "`.claude/skills/`; engines that bind skills by name check them against this list.", ""] + sections[:-1]
    else:
        out.append("None: no plug-in is pinned in this repository.")
    # Checkout-independent on purpose: a clone without submodules must render the same catalog.
    registered = read_gitmodules(root)
    out += ["", "## Plug-ins", "", "Add one with `python3 06_Engine/scripts/agency.py plugin add <name>`; "
            "see [PLUGINS.md](../00_README/PLUGINS.md). List a mounted plug-in's skills, agents and commands with "
            "`python3 06_Engine/scripts/agency.py plugin status <name>`.", "",
            "| Plug-in | Kind | In this repository | Editions | What it adds |", "|---|---|---|---|---|"]
    for name, state in catalog.states.items():
        profile = state.profile
        entry = registered.get(str(state.mount))
        if state.override.enabled is False:
            here = "hidden (agency.yaml)"
        elif entry:
            pinned_edition = edition_of_source(profile, entry.get("url", ""))
            here = f"pinned ({pinned_edition})" if pinned_edition else "pinned"
        else:
            here = "available"
        out.append(f"| {label(name)} | {profile.kind} | {here} | {', '.join(profile.editions)} | {prose(profile.summary)} |")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ENGINE_DIR.parent)
    parser.add_argument("--check", action="store_true", help="exit 1 when INDEX.md is stale; write nothing")
    args = parser.parse_args()
    target = args.root / INDEX
    new = render(args.root)
    current = target.read_text(encoding="utf-8") if target.is_file() else ""
    if args.check:
        if current != new:
            print("catalog: STALE — run python3 06_Engine/harness/build-skill-index.py", file=sys.stderr)
            return 1
        print("catalog: up to date")
        return 0
    if current != new:
        target.write_text(new, encoding="utf-8")
        print(f"catalog: wrote {INDEX}")
    else:
        print("catalog: unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
